// Writes `src/monaco.ts`: Monaco's editor and its features (find, folding, suggestions…)
// without the services of other languages (TypeScript, CSS, HTML, JSON: megabytes of
// workers) nor the diff editor. The list comes from Monaco's own full entry point; run
// this again after upgrading `monaco-editor` (`bun scripts/monaco-features.ts`).

const main = "node_modules/monaco-editor/esm/vs/editor/editor.main.js";
const { version } = await Bun.file("node_modules/monaco-editor/package.json").json();

const features = (await Bun.file(main).text())
  .split("\n")
  .map((line) => /^import '(\.\.?\/[^']+)\.js';$/.exec(line)?.[1])
  .filter((p): p is string => !!p && !p.includes("/definitions/") && !/diffEditor|gpu/.test(p))
  .map((p) => (p.startsWith("../") ? `monaco-editor/${p.slice(3)}` : `monaco-editor/editor/${p.slice(2)}`));

await Bun.write(
  new URL("../src/monaco.ts", import.meta.url),
  `// Generated by \`scripts/monaco-features.ts\` from monaco-editor ${version}: do not edit.\n\n` +
    `export * from "monaco-editor/editor";\n` +
    features.map((f) => `import "${f}";\n`).join(""),
);
console.log(`src/monaco.ts: ${features.length} features (monaco-editor ${version})`);
